"""GPL-3.0-only. Tables and figures from the wind Monte Carlo (sim/nav/run_wind_mc.py).

Usage: python sim/nav/analyse_wind_mc.py

Reads results/wind_mc/summary.json and writes tables.md and PNG charts beside
it. Everything is SYNTHETIC; see run_wind_mc.py for what was assumed.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from plotting import PALETTE, bar_chart, line_chart  # noqa: E402

OUT = HERE/'results'/'wind_mc'
ORDER = ('benign', 'mild', 'moderate', 'severe', 'violent')
NAMES = {'gps': 'GPS velocity, proposal J.1', 'trn': 'TRN velocity, proposal J.1',
         'trn_white': 'TRN velocity, error taken as white',
         'gps_glide_state_only': 'GPS, glide state but no airspeed',
         'gps_air': 'GPS + airspeed, offset found from spin only',
         'gps_air_cal': 'GPS + airspeed, offset from a hang test',
         'trn_air_cal': 'TRN + airspeed, offset from a hang test',
         'gps_air_cal_no_canopy_model': 'GPS + airspeed, no canopy model',
         'direct': 'GPS, direct inversion u + tau du/dt'}
SUB = 'SYNTHETIC: simulated descents, sensors and wind'


def main():
    report = json.loads((OUT/'summary.json').read_text())
    canopies = [c for c in ORDER if c in report['canopies']]
    data = report['canopies']
    need = report['requirement_mps']
    lines = ['# Wind Monte Carlo tables', '', 'SYNTHETIC. Generated by `sim/nav/analyse_wind_mc.py` from `summary.json`.',
             'Wind errors are RMS per horizontal axis of 20 m layer means, layers from 80 m to 300 m, against the',
             'simulated wind. %d descents per canopy class.' % data[canopies[0]]['descents'], '']

    lines += ['## Canopy classes as flown here', '',
              '| Class | Mean glide speed | Air-relative speed per axis | Yaw turned (median) | Navigation velocity error per axis |',
              '| --- | ---: | ---: | ---: | ---: |']
    for c in canopies:
        d = data[c]
        lines.append('| %s | %.2f m/s | %.2f m/s | %.1f turns | %.2f m/s |' % (
            c, d['true_glide_speed_mean'], d['airspeed_true_rms'], d['yaw_turns_median'],
            d['navigation_velocity_rms_per_axis']))

    lines += ['', '## Wind error against truth, 80-300 m (m/s; requirement %.1f)' % need, '',
              '| Retrieval | ' + ' | '.join(canopies) + ' |', '| --- |' + ' ---: |'*len(canopies)]
    for key, label in NAMES.items():
        lines.append('| %s | ' % label + ' | '.join('%.2f' % data[c]['wind'][key]['layer_rms_80_300'] for c in canopies) + ' |')

    lines += ['', '## Share of layer errors inside the stated 95 % interval, 80-300 m', '',
              '| Retrieval | ' + ' | '.join(canopies) + ' |', '| --- |' + ' ---: |'*len(canopies)]
    for key, label in NAMES.items():
        if key != 'direct':
            lines.append('| %s | ' % label + ' | '.join(
                '%.0f %%' % (100*data[c]['wind'][key]['coverage95_80_300']) for c in canopies) + ' |')

    lines += ['', '## S1: image-derived minus GPS-derived wind, 80-300 m (m/s)', '',
              '| Canopy | TRN minus GPS (J.1) | True error of the TRN wind | True error of the GPS wind | Trend of the difference per 100 m of height |',
              '| --- | ---: | ---: | ---: | ---: |']
    for c in canopies:
        s1 = data[c]['s1']['trn_minus_gps']
        lines.append('| %s | %.2f | %.2f | %.2f | %+.3f |' % (
            c, s1['layer_rms_80_300'], data[c]['wind']['trn']['layer_rms_80_300'],
            data[c]['wind']['gps']['layer_rms_80_300'], s1['slope_rms_per_100m']))

    lines += ['', '## Airspeed from lateral specific force (m/s per axis, per 2 s window)', '',
              '| Canopy | True air-relative speed | Error, offset from a hang test | Error, offset not removed |',
              '| --- | ---: | ---: | ---: |']
    for c in canopies:
        d = data[c]
        lines.append('| %s | %.2f | %.2f | %.2f |' % (c, d['airspeed_true_rms'], d['airspeed_sample_error_rms_calibrated'],
                                                    d['airspeed_sample_error_rms_uncalibrated']))

    heights = data[canopies[0]]['landing']['gps']['height_m']
    for c in canopies:
        lines += ['', '## Landing prediction, %s canopy' % c, '',
                  '| Predictor | Quantity | ' + ' | '.join('%.0f m' % h for h in heights) + ' |',
                  '| --- | --- |' + ' ---: |'*len(heights)]
        for key, label in (('gps', 'GPS'), ('trn', 'TRN'), ('dr', 'dead reckoning'), ('gps_glide', 'GPS, glide state'),
                           ('trn_glide', 'TRN, glide state')):
            d = data[c]['landing'][key]
            lines.append('| %s | radial RMS (m) | ' % label + ' | '.join('%.1f' % x for x in d['radial_rms_m']) + ' |')
            lines.append('| | stated 1-sigma (m) | ' + ' | '.join('%.1f' % x for x in d['stated_sigma_m']) + ' |')
            lines.append('| | inside 95 % ellipse | ' + ' | '.join('%.0f %%' % (100*x) for x in d['coverage95']) + ' |')
        lines.append('| all | touchdown time RMS (s) | ' + ' | '.join(
            '%.2f' % x for x in data[c]['landing']['gps']['time_error_rms_s']) + ' |')
    (OUT/'tables.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')

    def group(key, label, colour):
        return {'label': label, 'values': [data[c]['wind'][key]['layer_rms_80_300'] for c in canopies], 'color': colour}

    bar_chart(OUT/'wind_error.png', canopies, [
        group('gps', 'GPS velocity, proposal J.1', PALETTE[0]),
        group('trn', 'TRN velocity, proposal J.1', PALETTE[1]),
        group('gps_air', 'GPS + airspeed, spin only', PALETTE[4]),
        group('gps_air_cal', 'GPS + airspeed, hang test', PALETTE[2]),
        group('trn_air_cal', 'TRN + airspeed, hang test', PALETTE[3])],
        'Wind error against truth by canopy class', 'layer-mean wind error, RMS per axis (m/s)',
        SUB + '; 20 m layers, 80-300 m', hlines=[(need, 'requirement 0.5 m/s', '#B22222')])
    bar_chart(OUT/'s1_blind.png', canopies, [
        {'label': 'S1: image minus GPS wind', 'values': [data[c]['s1']['trn_minus_gps']['layer_rms_80_300'] for c in canopies],
         'color': PALETTE[5]},
        {'label': 'true error of the image wind', 'values': [data[c]['wind']['trn']['layer_rms_80_300'] for c in canopies],
         'color': PALETTE[1]}],
        'What the S1 comparison sees against the true error', 'RMS per axis in 20 m layers (m/s)',
        SUB + '; proposal J.1 retrieval', hlines=[(need, 'S1 criterion 0.5 m/s', '#B22222')])
    bar_chart(OUT/'wind_coverage.png', canopies, [
        {'label': 'GPS velocity, proposal J.1', 'values': [100*data[c]['wind']['gps']['coverage95_80_300'] for c in canopies],
         'color': PALETTE[0]},
        {'label': 'GPS + airspeed, hang test', 'values': [100*data[c]['wind']['gps_air_cal']['coverage95_80_300'] for c in canopies],
         'color': PALETTE[2]}],
        'Is the stated wind uncertainty honest?', 'layer errors inside the stated 95 % interval (%)', SUB,
        ylim=(0, 100), hlines=[(95, 'nominal 95 %', '#B22222')])
    centre = [e + 10.0 for e in report['layer_edges_m'][:-1]]
    for c in ('benign', 'moderate'):
        if c not in data:
            continue
        w = data[c]['wind']
        line_chart(OUT/f'wind_error_vs_height_{c}.png', [
            {'x': centre, 'y': w['gps']['layer_rms_by_layer'], 'label': 'GPS velocity, J.1', 'color': PALETTE[0]},
            {'x': centre[4:], 'y': w['trn']['layer_rms_by_layer'][4:], 'label': 'TRN velocity, J.1', 'color': PALETTE[1]},
            {'x': centre, 'y': w['gps_air_cal']['layer_rms_by_layer'], 'label': 'GPS + airspeed, hang test', 'color': PALETTE[2]},
            {'x': centre[4:], 'y': data[c]['s1']['trn_minus_gps']['layer_rms_by_layer'][4:], 'label': 'S1: image minus GPS',
             'color': PALETTE[5], 'style': 'dash'}],
            'Wind error against height, %s canopy' % c, 'height above ground (m)', 'layer-mean wind error, RMS per axis (m/s)',
            SUB, hlines=[(need, 'requirement', '#B22222')], invert_x=True)
        lp = data[c]['landing']
        line_chart(OUT/f'landing_error_{c}.png', [
            {'x': heights, 'y': lp['gps']['radial_rms_m'], 'label': 'GPS', 'color': PALETTE[0], 'style': 'line+points'},
            {'x': heights, 'y': lp['trn']['radial_rms_m'], 'label': 'TRN', 'color': PALETTE[1], 'style': 'line+points'},
            {'x': heights, 'y': lp['dr']['radial_rms_m'], 'label': 'dead reckoning', 'color': PALETTE[6], 'style': 'line+points'},
            {'x': heights, 'y': lp['gps_glide']['radial_rms_m'], 'label': 'GPS, glide state', 'color': PALETTE[2], 'style': 'dash'},
            {'x': heights, 'y': lp['trn_glide']['radial_rms_m'], 'label': 'TRN, glide state', 'color': PALETTE[3], 'style': 'dash'}],
            'Landing prediction error against height, %s canopy' % c, 'height when the prediction was made (m)',
            'radial error of the predicted touchdown point, RMS (m)', SUB, logy=True, invert_x=True)
    bar_chart(OUT/'landing_coverage.png', canopies, [
        {'label': 'GPS', 'values': [100*data[c]['landing']['gps']['coverage95'][3] for c in canopies], 'color': PALETTE[0]},
        {'label': 'TRN', 'values': [100*data[c]['landing']['trn']['coverage95'][3] for c in canopies], 'color': PALETTE[1]},
        {'label': 'GPS, glide state', 'values': [100*data[c]['landing']['gps_glide']['coverage95'][3] for c in canopies],
         'color': PALETTE[2]},
        {'label': 'TRN, glide state', 'values': [100*data[c]['landing']['trn_glide']['coverage95'][3] for c in canopies],
         'color': PALETTE[3]}],
        'Is the landing ellipse honest? Predictions made at 100 m', 'touchdowns inside the 95 % ellipse (%)', SUB,
        ylim=(0, 100), hlines=[(95, 'nominal 95 %', '#B22222')])
    print('wrote', OUT/'tables.md')


if __name__ == '__main__':
    main()
