"""GPL-3.0-only. Deterministic host oracle vectors for CORE-B (no hardware)."""
from pathlib import Path
import math
import sys
import numpy as np

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / 'code'))
sys.path.insert(0, str(ROOT / 'sim' / 'temperature'))
from cansat import atmosphere, flight_state, geo, lora, downlink
import models

OUT = Path(__file__).resolve().parents[1] / 'tests' / 'vectors_core_b.h'

def num(x):
    return '(double)NAN' if math.isnan(x) else format(float(x), '.17g')

def main():
    lines = ['/* GPL-3.0-only. Generated by tools/gen_core_b_vectors.py; synthetic Python oracle. */',
             '#ifndef VECTORS_CORE_B_H', '#define VECTORS_CORE_B_H']
    rows = []
    # Sensor-independent acceleration and timeouts, pressure-only flight,
    # transient spikes, pressure gaps, fast bounded update rate, no pad wait.
    for scenario in range(6):
        f = flight_state.FlightStateMachine()
        rate = 100 if scenario == 4 else 10
        end = 10 if scenario == 4 else 210 if scenario in (0, 5) else 65
        for k in range(end * rate):
            t = k / rate
            height = 0 if t < 5 else min(300, (t-5)*90) if t < 9 else max(0, 300-(t-9)*10)
            p = atmosphere.pressure_at(height, 101325, f.cfg.mean_temp_k)
            acc = 9.80665
            if scenario in (0, 3, 4, 5):
                if (5 <= t < 5.6) or (10 <= t < 10.1): acc = 80
                if 40 <= t < 40.2: acc = 100
            if scenario == 0: p = math.nan
            if scenario == 2:
                acc = 100 if 2 <= t < 2.05 else math.nan
                if k % 11 == 0: p = math.nan
            if scenario == 3 and (15 < t < 18 or 30 < t < 45): p = math.nan
            if scenario == 5:
                acc = 80 if t < .4 else math.nan
                p = math.nan
            f.update(t, acc, p)
            reason = 0 if not f.events else {'acceleration':1, 'altitude':2, 'timeout':3}[f.events[-1][2]]
            rows.append((scenario, t, acc, p, f.state.value, reason, len(f.events),
                         f.baseline_pa if f.baseline_pa is not None else math.nan,
                         f.altitude, f.vertical_speed, f.max_altitude))
    lines += ['typedef struct { unsigned scenario; double t, accel, p; unsigned state, reason, events; double baseline, altitude, speed, maximum; } fsm_vector_t;',
              'static const fsm_vector_t fsm_vectors[] = {']
    for row in rows:
        lines.append('    {' + ','.join(str(v) if j in (0,4,5,6) else num(v) for j,v in enumerate(row)) + '},')
    lines.append('};')
    lines += ['typedef struct { unsigned bytes,sf,cr; double bw; unsigned crc,implicit; int ldro; double toa; } lora_vector_t;', 'static const lora_vector_t lora_vectors[] = {']
    for sf in range(6,13):
        for bw in (62500,125000,250000):
            for cr in (1,4):
                for n in (0,40,255):
                    for implicit in (False,True):
                        for crc in (False,True):
                            for ldro in (None,False,True):
                                toa = lora.time_on_air(n,sf,bw,cr,crc=crc,implicit_header=implicit,ldro=ldro)
                                lines.append(f'    {{{n},{sf},{cr},{bw},{int(crc)},{int(implicit)},{-1 if ldro is None else int(ldro)},{num(toa)}}},')
    lines.append('};')
    s = downlink.DownlinkScheduler(.06,.01)
    due = [k for k in range(127200) if s.due(k*.1, flight_state.State.PAD if k<108000 else flight_state.State.DESCENT if k<109200 else flight_state.State.LANDED)]
    lines += ['static const unsigned downlink_due_ticks[] = {' + ','.join(map(str,due)) + '};']
    lines += ['typedef struct { int32_t lat,lon,h,lat0,lon0,h0; double e,n,u; } geo_vector_t;', 'static const geo_vector_t geo_vectors[] = {']
    for args in ((223000000,1142000000,50000,223000000,1142000000,50000),
                 (223017234,1142122345,320000,223000000,1142000000,50000),
                 (-899999000,-1799999000,-5000,-899999900,1799999000,0),
                 (899999999,1799999999,100000,890000000,-1799999999,50000),
                 (-450000000,10000000,300000,-450005000,9990000,12000)):
        lines.append('    {' + ','.join(map(str,args)) + ',' + ','.join(num(v) for v in geo.enu_from_link(*args)) + '},')
    lines.append('};')
    lines += ['typedef struct { int16_t a,b; unsigned pga0,pga1,sh; float r; int centi; } ntc_vector_t;', 'static const ntc_vector_t ntc_vectors[] = {']
    for sh in (False,True):
        for tc in np.linspace(-20,50,29):
            r = float(models.nominal_resistance(tc)); v = float(models.divider(r)[0])
            a=int(models.adc_code(v,2.048)); b=int(models.adc_code(3.,4.096))
            observed=float(models.resistance_from_volts(models.code_volts(a,2.048),models.code_volts(b,4.096)))
            temp=float(models.sh_temperature(observed,models.SH_COEFF) if sh else models.beta_temperature(observed))
            lines.append(f'    {{{a},{b},2,1,{int(sh)},{observed:.9f}f,{math.floor(temp*100+.5)}}},')
    lines += ['};', 'static const float ntc_sh_coeff[3] = {' + ','.join(f'{x:.12g}f' for x in models.SH_COEFF) + '};', '#endif']
    OUT.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(f'{OUT}: {len(rows)} FSM rows, {len(due)} downlink sends')

if __name__ == '__main__': main()
